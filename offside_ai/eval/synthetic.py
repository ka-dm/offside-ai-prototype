"""Tiny synthetic evaluation set (no copyrighted footage)."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import soundfile as sf

from offside_ai.audio.detect import AudioPassConfig, detect_pass_from_audio
from offside_ai.common import ensure_dir
from offside_ai.offside.geometry import (
    AttackingDirection,
    PlayerPoseOnPitch,
    compute_offside,
)

from .metrics import evaluate_annotations
from .schema import ANNOTATION_COLUMNS


def synthesize_kick_wav(
    path: Path,
    sr: int = 22050,
    duration_s: float = 2.0,
    kick_time_s: float = 0.8,
) -> Path:
    """Write a silent clip with a short mid-band burst at ``kick_time_s``."""
    t = np.arange(int(sr * duration_s)) / sr
    y = 0.01 * np.random.randn(len(t)).astype(np.float64)
    # Decaying sinusoid burst ~1.2 kHz (inside default band-pass)
    burst_len = int(0.025 * sr)
    i0 = int(kick_time_s * sr)
    i1 = min(len(y), i0 + burst_len)
    tb = np.arange(i1 - i0) / sr
    burst = 0.9 * np.sin(2 * np.pi * 1200 * tb) * np.exp(-tb * 80)
    y[i0:i1] += burst
    path.parent.mkdir(parents=True, exist_ok=True)
    sf.write(str(path), y, sr)
    return path


def build_synthetic_eval_dir(root: str | Path) -> Path:
    """Create WAV kicks + annotation/prediction CSVs + geometry cases."""
    root = ensure_dir(root)
    audio_dir = ensure_dir(root / "audio")
    rows = []
    pred_rows = []
    kicks = [
        ("syn_001", 0.80, 25.0),
        ("syn_002", 1.20, 30.0),
        ("syn_003", 0.50, 25.0),
    ]
    cfg = AudioPassConfig(av_offset_s=0.0, top_k=3)
    for clip_id, kick_t, fps in kicks:
        wav = synthesize_kick_wav(audio_dir / f"{clip_id}.wav", kick_time_s=kick_t)
        result = detect_pass_from_audio(wav_path=wav, fps=fps, cfg=cfg)
        assert result.best is not None
        gt_frame = int(round(kick_t * fps))
        rows.append(
            {
                "clip_id": clip_id,
                "clip_path": str(wav),
                "fps": fps,
                "gt_pass_frame": gt_frame,
                "gt_decision": "offside" if clip_id != "syn_002" else "onside",
                "gt_margin_m": 0.25 if clip_id != "syn_002" else -0.10,
                "attacking_team_id": 0,
                "attacking_direction": "positive_x",
                "source": "synthetic",
                "credits": "generated by offside_ai.eval.synthetic",
                "notes": "",
            }
        )
        # Geometry synthetic decision for the same clip_id
        if clip_id == "syn_002":
            players = [
                PlayerPoseOnPitch(1, 1, 40.0, role="goalkeeper"),
                PlayerPoseOnPitch(2, 1, 55.0),
                PlayerPoseOnPitch(3, 1, 60.0),
                PlayerPoseOnPitch(10, 0, 59.5),  # onside (behind second-last at 60? wait)
            ]
            # second-last = 55 if ranked 60,55,... attacking +x; attacker 59.5 < 55? No 59.5 > 55
            # Fix: attacker behind line for onside
            players = [
                PlayerPoseOnPitch(1, 1, 40.0, role="goalkeeper"),
                PlayerPoseOnPitch(2, 1, 60.0),
                PlayerPoseOnPitch(3, 1, 58.0),
                PlayerPoseOnPitch(10, 0, 57.5),  # behind second-last 58
            ]
        else:
            players = [
                PlayerPoseOnPitch(1, 1, 40.0, role="goalkeeper"),
                PlayerPoseOnPitch(2, 1, 60.0),
                PlayerPoseOnPitch(3, 1, 58.0),
                PlayerPoseOnPitch(10, 0, 59.0),  # beyond 58
            ]
        decision = compute_offside(players, 0, AttackingDirection.POSITIVE_X)
        pred_rows.append(
            {
                "clip_id": clip_id,
                "pred_pass_frame": result.best.frame_index,
                "pred_decision": "offside" if decision.is_offside else "onside",
                "pred_margin_m": max(decision.margins_m.values()) if decision.margins_m else 0.0,
                "audio_confidence": result.best.confidence,
            }
        )

    ann_path = root / "annotations.csv"
    pred_path = root / "predictions.csv"
    pd.DataFrame(rows, columns=ANNOTATION_COLUMNS).to_csv(ann_path, index=False)
    pd.DataFrame(pred_rows).to_csv(pred_path, index=False)
    report = evaluate_annotations(pd.read_csv(ann_path), pd.read_csv(pred_path))
    (root / "report.json").write_text(
        __import__("json").dumps(report.to_dict(), indent=2)
    )
    return root
